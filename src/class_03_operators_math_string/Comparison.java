package class_03_operators_math_string;
public class Comparison{
    public static void main(String[] args){
        //Comparison operators are used to compare two values.

        // Equal to (==) operator
        int a = 10;
        int b = 5;
        System.out.println(a == b); // returns false because 10 is not equal to 5

        // Not equal to (!=) operator
        System.out.println(a != b); // returns true because 10 is not equal to 5

        // Greater than (>) operator
        System.out.println(a > b); // returns true because 10 is greater than 5

        // Less than (<) operator
        System.out.println(a < b); // returns false because 10 is not less than 5

        // Greater than or equal to (>=) operator
        System.out.println(a >= b); // returns true because 10 is greater than or equal to 5

        // Less than or equal to (<=) operator
        System.out.println(a <= b); // returns false because 10 is not less than or equal to 5

    }

}